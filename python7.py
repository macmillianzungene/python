
# Arimthmetic ops
# + Addition Adds two values together:                                    10 + 3 = 13
# - Subtraction Subtracts the right value from the left:                  10 - 7 = 7
# * Multiplication Multiplies two values:                                 10 * 3 = 30
# / Division Divides and always returns a decimal float:                  10 / 4 = 2.5
# // Floor Division Divides and rounds down to the nearest whole integer: 10 // 4 = 2 
# % Modulus Returns the remainder left over after division:               10 % 4 = 2 
# ** Exponentiation Raises the left number to the power of the right:     2 ** 3 = 8  

# Comparisons:
# Equal:               3 == 2
# Not equal:           3 != 2
# Greater than:        3 >  2
# Less than:           3 <  2
# Greater or eqaul to: 3 >= 2
# Less or equal to:    3 <= 2

